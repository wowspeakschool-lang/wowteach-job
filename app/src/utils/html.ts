// В legacy вся разметка собиралась строками, поэтому esc() был обязателен.
// В React экранирование по умолчанию, и esc нужен только там, где мы
// осознанно вставляем сырой HTML из базы (оффер, материалы, справочник,
// описания шагов) — вокруг него, а не вместо него.
export const esc = (s: unknown): string =>
  String(s ?? '').replace(
    /[&<>"']/g,
    (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c] ?? c,
  );
